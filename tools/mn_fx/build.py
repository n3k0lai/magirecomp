# Build src/mn/fx/Blocks.lua: the game's SM83 basic blocks translated to Lua.
# usage: python3 tools/mn_fx/build.py <rom> tools/mn_fx/executed.txt src/mn/fx/Blocks.lua [sym] --only tools/mn_fx/executed.txt
# executed.txt lists the blocks the generator's runs enter (tools/mn_fx/executed.lua), so only code
# that runs is translated; nothing from the ROM besides instruction operands ends up in the output.
import sys
import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from translate import translate_block
args = [a for a in sys.argv[1:] if not a.startswith('--')]
ROM, SEEDS, OUT = args[0], args[1], args[2]
SYM = args[3] if len(args) > 3 else None
only = None
if '--only' in sys.argv:
    only = set()
    for ln in open(sys.argv[sys.argv.index('--only') + 1]):
        b, a = ln.strip().split(':'); only.add((int(b, 16), int(a, 16)))
rom = open(ROM, 'rb').read()
names = {}
if SYM:
    for ln in open(SYM):
        if ln.startswith(';') or ':' not in ln: continue
        a, n = ln.split()[:2]; b, ad = a.split(':'); b = int(b, 16); ad = int(ad, 16)
        if ad < 0x8000 and '.' not in n: names.setdefault((b if ad >= 0x4000 else 0, ad), n)
def rdf(bank):
    def rd(a):
        a &= 0xFFFF
        if a < 0x4000: return rom[a]
        if a < 0x8000: return rom[bank * 0x4000 + a - 0x4000]
        raise IndexError('code read outside ROM %04X' % a)
    return rd
seeds = []
for ln in open(SEEDS):
    ln = ln.split('#')[0].strip()
    if not ln: continue
    b, a = ln.split(':'); seeds.append((int(b, 16), int(a, 16)))
done = {}; work = list(seeds)
while work:
    b, pc = work.pop()
    if pc < 0x4000: b = 0
    if pc >= 0x8000 or (b, pc) in done: continue
    if only is not None and (b, pc) not in only: continue
    try: body, succ, calls, end, ents = translate_block(rdf(b), pc)
    except IndexError: continue
    done[(b, pc)] = (body, ents)
    for t in succ + calls:
        if t < 0x8000: work.append((0 if t < 0x4000 else b, t))
out = ['-- Generated by tools/mn_fx/build.py: SM83 routines of the game, translated to Lua.',
       '-- Do not edit; regenerate. One function per basic block, keyed bank*0x10000+address.',
       'return function(env)',
       'local band, bor, bxor, lshift, rshift = bit.band, bit.bor, bit.bxor, bit.lshift, bit.rshift',
       'local rd, wr, daa = env.R, env.W, env.daa',
       'local HALTI, STOPI, DII, EII, RETI = env.halt, env.stop, env.di, env.ei, env.reti',
       'local A, B, C, D, E, H, L, SP, FZ, FN, FH, FC = 0,0,0,0,0,0,0,0,false,false,false,false',
       'local CY, LIM = 0, 0',
       'local K = {}']
kk = lambda b, a: b * 0x10000 + a if a >= 0x4000 else a
owner = {}
for (b, pc) in sorted(done):
    owner[kk(b, pc)] = (kk(b, pc), 0)
for (b, pc) in sorted(done):
    for i, a in enumerate(done[(b, pc)][1]):
        owner.setdefault(kk(b, a), (kk(b, pc), i + 1))
for (b, pc) in sorted(done):
    key = kk(b, pc)
    nm = names.get((b, pc))
    out.append('K[%d] = function(e) -- %02X:%04X%s' % (key, b, pc, (' ' + nm) if nm else ''))
    out.append('    ' + done[(b, pc)][0])
    out.append('end')
out.append('local E = {}')
for k in sorted(owner):
    f, i = owner[k]
    if i: out.append('K[%d] = K[%d]; E[%d] = %d' % (k, f, k, i))
out.append('env.entry = E')
out.append('''env.regs = function() return {A=A,B=B,C=C,D=D,E=E,H=H,L=L,SP=SP,FZ=FZ,FN=FN,FH=FH,FC=FC} end
env.setregs = function(r) A,B,C,D,E,H,L,SP,FZ,FN,FH,FC = r.A,r.B,r.C,r.D,r.E,r.H,r.L,r.SP,r.FZ,r.FN,r.FH,r.FC end
env.cy = function(v) if v then CY = v end return CY end
env.lim = function(v) if v then LIM = v end return LIM end
env.sp = function(v) if v then SP = v end return SP end
env.a = function(v) if v then A = v end return A end
env.hl = function() return H*256+L end
env.zf = function(v) if v ~= nil then FZ = v end return FZ end
return K
end''')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('blocks', len(done))
