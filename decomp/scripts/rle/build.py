#!/usr/bin/env python3
"""Encode src/tilemaps/*/*.tmap into out/gen/tilemaps/bankXX_XXXX.asm.

Back-to-back streams in one bank are joined into one file named by the first
stream. The scaffold INCLUDEs that file where the stream run sits.
"""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts/rle"))
from rlelib import read_tmap  # noqa: E402

def runs():
    out = []
    for d in sorted((ROOT / "src/tilemaps").glob("bank??")):
        bank = int(d.name[4:], 16); cur = None
        for f in sorted(d.glob("*.tmap")):
            addr = int(f.stem, 16); enc = read_tmap(f)
            if cur and cur[2] == addr:
                cur[3].append((addr, enc)); cur[2] = addr + len(enc)
            else:
                cur = [bank, addr, addr + len(enc), [(addr, enc)]]; out.append(cur)
    return out

def main():
    gen = ROOT / "out/gen/tilemaps"; gen.mkdir(parents=True, exist_ok=True)
    for bank, start, end, items in runs():
        lines = [f"; generated by scripts/rle/build.py from src/tilemaps/bank{bank:02X}"]
        for addr, enc in items:
            lines.append(f"Tilemap_{bank:02X}_{addr:04X}::")
            for i in range(0, len(enc), 16):
                lines.append("    db " + ", ".join(f"${b:02X}" for b in enc[i:i + 16]))
        text = "\n".join(lines) + "\n"
        f = gen / f"bank{bank:02X}_{start:04X}.asm"
        if not f.exists() or f.read_text() != text: f.write_text(text)
    if "--runs" in sys.argv:
        for bank, start, end, _ in runs(): print(f"{bank:02X} {start:04X} {end:04X}")

if __name__ == "__main__":
    main()
