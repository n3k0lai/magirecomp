#!/usr/bin/env python3
"""Generate src/wave_frames_bank31.asm: the 16-byte wave-RAM frames at the
head of bank $31 that the four WaveRecords in bank $30 point at (pointer,
frame count; bank byte = $31 - $30). Each frame is 32 4-bit samples
written to wave RAM ($FF30-$FF3F). Records: $4000 x12, $40C0, $40D0, $40E0.
$40F0-$41FF is zero. $4200-$7FFF is never addressed by code: it is a
leftover from the developer's build disk (a DOS program stub, then a
gm2song / file-checksum listing) and stays INCBIN.
"""
d = open("roms/magination.gbc", "rb").read()
B = 0x31 * 0x4000
GROUPS = [("WaveFramesA", 0x4000, 12), ("WaveFramesB", 0x40C0, 1),
          ("WaveFramesC", 0x40D0, 1), ("WaveFramesD", 0x40E0, 1)]
o = ["; Bank $31: wave-RAM frames for the sound engine. Generated by",
     "; scripts/own/gen_wave_frames.py. Each 16-byte row is one frame of 32 4-bit samples",
     "; (two per byte, high nibble first) for $FF30-$FF3F.", ""]
for name, a, n in GROUPS:
    o.append(f"{name}::  ; ${a:04X}, {n} frame{'s' if n > 1 else ''}")
    for k in range(n):
        f = d[B + a - 0x4000 + 16 * k:B + a - 0x4000 + 16 * k + 16]
        o.append("    db " + ", ".join(f"${v:02X}" for v in f))
    o.append("")
o.append("WaveFramesEnd::")
o.append("    ds $4200 - $40F0, $00 ; zero to $4200")
o.append("")
open("src/wave_frames_bank31.asm", "w").write("\n".join(o))
