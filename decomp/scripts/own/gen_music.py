#!/usr/bin/env python3
"""Generate src/music_bankNN.asm for banks $32-$3C from the ROM.

Songs come from the 41-entry list at $5A79 + [$5A85] in bank $30. Each
song is decoded with scripts/own/music_format.py, and every byte of each
bank's data is placed inside exactly one decoded item (checked).
"""
import collections, sys
sys.path.insert(0, "scripts/own")
from music_format import d, songs, Song

items_by_bank = collections.defaultdict(dict)   # addr -> (end, text lines)
labels = collections.defaultdict(dict)          # bank -> addr -> label


def lab(b, a, name):
    labels[b].setdefault(a, name)
    return labels[b][a]


def main():
    S = songs()
    first = {}
    for i, (b, p) in enumerate(S):
        first.setdefault((b, p), i)
    song_objs = []
    for (b, p), i in sorted(first.items(), key=lambda kv: kv[1]):
        s = Song(b, p)
        nm = f"Song{i:02d}"
        song_objs.append((nm, s))
        lab(b, p, nm)
        lab(b, s.T, nm + "_Table")
        lab(b, s.trk_tab, nm + "_Tracks")
        lab(b, s.pat_tab, nm + "_Patterns")
        for n, t in enumerate(s.tracks):
            if t:
                lab(b, t[0], f"{nm}_Track{n}")
        for n, pt in enumerate(s.pats):
            lab(b, pt[0], f"{nm}_Pattern{n:02d}")
    for nm, s in song_objs:
        b, R = s.bank, s.R
        BE = lambda a: R(a) << 8 | R(a + 1)
        L = labels[b]
        T = L[s.T]
        it = items_by_bank[b]

        def put(a, end, lines):
            if a in it:
                assert it[a][0] == end, (hex(b), hex(a))
                return
            it[a] = (end, lines)
        hdr = [f"    db " + ", ".join(f"${R(s.p + k):02X}" for k in range(4)) + "  ; starting program per slot ($DFAD-$DFB0)",
               f".program_map  ; ReadIndexedCountdownByte: program -> instrument"]
        for r in range(0, 128, 16):
            hdr.append("    db " + ", ".join(f"${R(s.p + 4 + r + k):02X}" for k in range(16)))
        put(s.p, s.p + 0x84, hdr)
        put(s.T, s.T + 6, [f"    bigw {L[s.trk_tab]} - {T}", f"    bigw {L[s.pat_tab]} - {T}",
                           f"    bigw ${BE(s.T + 4):04X}  ; tempo (ReadCountdownScale)"])
        lines = []
        for n in range(4):
            w = BE(s.trk_tab + 2 * n)
            lines.append(f"    bigw {L[s.T + w]} - {T}" if w else "    bigw 0")
        put(s.trk_tab, s.trk_tab + 8, lines)
        put(s.pat_tab, s.pat_tab + 2 * len(s.pats),
            [f"    bigw {L[s.T + BE(s.pat_tab + 2 * i)]} - {T}" for i in range(len(s.pats))])
        for n, t in enumerate(s.tracks):
            if not t:
                continue
            start, end, recs = t
            ln = []
            for kind, a in recs:
                dl = BE(a)
                if kind == "rec":
                    ln.append(f"    trk_play ${dl:04X}, ${R(a + 2):02X}")
                else:
                    add = BE(a + 3)
                    tgt = start + add
                    # the addend is from the slot's track start (the track table word)
                    addexpr = f"{L[tgt]} - {L[start]}" if tgt in L and add else f"${add:04X}"
                    m = "trk_end" if kind == "end" else "trk_loop"
                    ln.append(f"    {m} ${dl:04X}, {addexpr}, ${BE(a + 5):04X}")
            put(start, end, ln)
        for n, (start, end, ev) in enumerate(s.pats):
            ln = []
            for kind, a, size in ev:
                tag, dl = R(a) >> 4, (R(a) & 0xF) << 8 | R(a + 1)
                b2 = R(a + 2)
                if kind == "end":
                    ln.append(f"    ev_end ${dl:03X}")
                elif kind == "prog":
                    ln.append(f"    ev_prog ${dl:03X}, ${b2 & 0x7F:02X}")
                else:
                    o = a + 3
                    if b2 & 0x80:
                        prog = R(o); o += 1
                    if R(o) & 0x80:
                        span, lng = (R(o) & 0x7F) << 8 | R(o + 1), True
                    else:
                        span, lng = R(o), False
                    long_needed = lng and span < 0x80
                    sfx = "_long" if long_needed else ""
                    if b2 & 0x80:
                        ln.append(f"    ev_note_prog{sfx} ${tag:X}, ${dl:03X}, ${b2 & 0x7F:02X}, ${prog:02X}, ${span:04X}")
                    else:
                        ln.append(f"    ev_note{sfx} ${tag:X}, ${dl:03X}, ${b2:02X}, ${span:04X}")
            put(start, end, ln)
    for b in sorted(items_by_bank):
        it = items_by_bank[b]
        x = d[b * 0x4000:(b + 1) * 0x4000]
        t = len(x.rstrip(b"\0")) + 0x4000
        out = [f"; Bank ${b:02X} songs, generated by scripts/own/gen_music.py.",
               "; Format: scripts/own/music-format.md.", "", 'INCLUDE "src/music_macros.inc"', ""]
        a = 0x4000
        for s_a in sorted(it):
            end, lines = it[s_a]
            assert s_a == a, (hex(b), hex(s_a), hex(a))
            nm = labels[b].get(s_a)
            if nm:
                out.append(("" if "_" in nm else "\n") + f"{nm}::")
            out += lines
            a = end
        assert a == t, (hex(b), hex(a), hex(t))
        open(f"src/music_bank{b:02x}.asm", "w").write("\n".join(out) + "\n")
        print(f"{b:02X} {t - 0x4000:04X}")


if __name__ == "__main__":
    main()
