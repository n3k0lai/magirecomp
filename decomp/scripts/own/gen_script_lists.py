#!/usr/bin/env python3
"""Generate src/script_lists_bank21.asm: the event-script entry lists at
the head of bank $21 ($4000-$5CBF, 572 lists, 1697 entries).

Each list is a count byte, then that many 4-byte entries:
    key, script bank, script pointer (little endian)
RunBank21ScriptList (bank 0 $2C97) walks a list: key $01 loads the
(bank, pointer) into the third script record and runs it; any other key
(0, 2-4 seen) skips the entry. The
lists chain with no gaps from $4000 to $5CBF; the RGB555 palettes that
follow are left INCBIN.

Script targets are named ScriptBB_PPPP, the label convention of the
data-script track (scripts/script/gen_event_scripts.py). By default the
entries are numeric, so this branch builds on its own. With --labels,
every target whose ScriptBB_PPPP:: label is defined somewhere under
src/ is written as BANK(label)/label instead (use after merging).
"""
import pathlib, re, sys

d = open("roms/magination.gbc", "rb").read()
b = d[0x21 * 0x4000:0x22 * 0x4000]
END = 0x1CC0


def parse():
    o, lists = 0, []
    while o < END:
        c = b[o]
        ents = [(b[o + 1 + 4 * i], b[o + 2 + 4 * i], b[o + 3 + 4 * i] | b[o + 4 + 4 * i] << 8)
                for i in range(c)]
        for k, bk, p in ents:
            assert k <= 8 and 2 <= bk < 0x50 and 0x4000 <= p < 0x8000, hex(o)
        lists.append((0x4000 + o, ents))
        o += 1 + 4 * c
    assert o == END
    return lists


def main():
    known = set()
    if "--labels" in sys.argv:
        for f in pathlib.Path("src").rglob("*.asm"):
            known |= set(re.findall(r"^(Script[0-9A-F]{2}_[0-9A-F]{4})::", f.read_text(errors="ignore"), re.M))
    lists = parse()
    out = ["; Bank $21 $4000-$5CBF: event-script entry lists. Generated by",
           "; scripts/own/gen_script_lists.py. Each list: count, then entries of",
           "; key, script bank, script pointer. RunBank21ScriptList runs the",
           "; entries keyed $01 and skips the rest.", "",
           "MACRO script_list", "    db \\1 ; entries", "ENDM", "",
           "; key, bank, pointer", "MACRO script_entry", "    db \\1, \\2", "    dw \\3", "ENDM", "",
           "; key, label (after the script banks are merged)", "MACRO script_entry_far",
           "    db \\1, BANK(\\2)", "    dw \\2", "ENDM", ""]
    for a, ents in lists:
        out.append(f"ScriptList21_{a:04X}::")
        out.append(f"    script_list {len(ents)}")
        for k, bk, p in ents:
            lab = f"Script{bk:02X}_{p:04X}"
            if lab in known:
                out.append(f"    script_entry_far {k}, {lab}")
            else:
                out.append(f"    script_entry {k}, ${bk:02X}, ${p:04X} ; {lab}")
    out.append("ScriptListsEnd::")
    out.append("")
    open("src/script_lists_bank21.asm", "w").write("\n".join(out))
    print(len(lists), sum(len(e) for _, e in lists))


if __name__ == "__main__":
    main()
