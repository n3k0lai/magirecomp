#!/usr/bin/env python3
"""Write the "still INCBIN" part of scripts/own/bank-survey.md.

usage: remaining_survey.py INTEGRATION_REPO [REF]
A byte counts as remaining when it is INCBIN from the ROM both in the
integration branch (all tracks merged) and on this branch. Read-only on the
integration repo (git grep on REF, default integration).
"""
import collections, re, subprocess, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
RX = re.compile(r'INCBIN\s+"roms/magination\.gbc"\s*,\s*\$([0-9A-Fa-f]+)\s*,\s*\$([0-9A-Fa-f]+)')

CATS = [
    ("event-script residue (data-script track)", list(range(0x12, 0x20)) + [0x22, 0x23, 0x28, 0x2A, 0x2B, 0x2E, 0x2F],
     "gaps between decoded event scripts: unreached scripts, text, small tables"),
    ("sprite-animation bytecode (data-script track)", [0x0E, 0x0F, 0x10, 0x11, 0x20, 0x25, 0x40],
     "script opcodes $46/$4C/$4D after the sprite lists; data-script has started seeding these"),
    ("gaps in RLE banks (data-rle track)", [0x26, 0x29, 0x43, 0x46, 0x49, 0x4A, 0x4B, 0x4D] + list(range(0x61, 0x7D)),
     "bytes between found UnpackBytes streams; much is 2bpp-looking; $7C also holds BG palettes"),
    ("graphics-bank leftovers", [0x24, 0x27, 0x41, 0x42, 0x50, 0x52, 0x53],
     "tails after converted tiles: records, sprite lists, font layout, unknown codec ($53)"),
    ("build-disk leftover", [0x31], "DOS stub + gm2song listing in bank $31, unreferenced"),
    ("zero tail still INCBIN", [0x4C], "bank $4C $5D2C-$7FFF is $00 (one nonzero byte at $5D2C)"),
    ("tables", [0x21], "bank $21 after the palettes: scripts and text"),
    ("sound", [0x30], "small gaps in the sound bank"),
    ("code banks", [0x00, 0x01], "header/logo and one small gap"),
]


def ranges(repo, ref):
    out = subprocess.run(["git", "-C", str(repo), "grep", "-h", "-E", 'INCBIN +"roms/magination', ref, "--", "src"],
                         capture_output=True, text=True).stdout
    s = bytearray(0x200000)
    for l in out.splitlines():
        m = RX.search(l.split(";")[0])
        if m:
            a, n = int(m.group(1), 16), int(m.group(2), 16)
            s[a:a + n] = b"\1" * n
    return s


def main():
    repo = Path(sys.argv[1]); ref = sys.argv[2] if len(sys.argv) > 2 else "integration"
    head = subprocess.run(["git", "-C", str(repo), "rev-parse", "--short", ref], capture_output=True, text=True).stdout.strip()
    mine = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    I = ranges(repo, ref); O = ranges(ROOT, "HEAD")
    rem = bytes(a & b for a, b in zip(I, O))
    rom = (ROOT / "roms/magination.gbc").read_bytes()
    per = {}
    for bk in range(0x80):
        s = bk * 0x4000; runs = []; i = s
        while i < s + 0x4000:
            if rem[i]:
                j = i
                while j < s + 0x4000 and rem[j]: j += 1
                runs.append((i, j)); i = j
            else: i += 1
        if runs: per[bk] = runs
    total = sum(rem)
    L = ["## Still INCBIN (remaining bytes)", "",
         f"Generated by `scripts/own/remaining_survey.py` against integration `{head}` and own-workers `{mine}`.",
         "A byte is remaining when both branches still INCBIN it from the ROM.",
         f"**Total remaining: {total} bytes ({total / 0x200000 * 100:.2f}% of the ROM).**", "",
         "| category | bytes | banks | notes |", "|---|---:|---|---|"]
    seen = set()
    for name, banks, note in CATS:
        bs = [b for b in banks if b in per]; seen |= set(bs)
        n = sum(e - s for b in bs for s, e in per[b])
        L.append(f"| {name} | {n} | {', '.join('$%02X' % b for b in bs)} | {note} |")
    other = [b for b in per if b not in seen]
    if other:
        n = sum(e - s for b in other for s, e in per[b])
        L.append(f"| uncategorised | {n} | {', '.join('$%02X' % b for b in other)} | |")
    L += ["", "| bank | remaining B | runs | zero B | largest runs (CPU addr, length) |", "|---|---:|---:|---:|---|"]
    for bk, runs in per.items():
        n = sum(e - s for s, e in runs)
        z = sum(1 for s, e in runs for k in range(s, e) if rom[k] == 0)
        big = sorted(runs, key=lambda r: r[0] - r[1])[:3]
        L.append(f"| ${bk:02X} | {n} | {len(runs)} | {z} | " +
                 ", ".join(f"${s % 0x4000 + (0x4000 if bk else 0):04X}+{e - s}" for s, e in big) + " |")
    md = ROOT / "scripts/own/bank-survey.md"
    text = md.read_text()
    text = re.sub(r"\n## Still INCBIN \(remaining bytes\).*", "", text, flags=re.S)
    md.write_text(text.rstrip() + "\n\n" + "\n".join(L) + "\n")
    print(total)


if __name__ == "__main__":
    main()
