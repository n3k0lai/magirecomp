#!/usr/bin/env python3
"""UnpackBytes-packed tile graphics: decoded tiles as PNG, packed at build time.

    rle_gfx.py extract BANK START END NAME   (development: needs the local ROM)
    rle_gfx.py build                         (run by make before rgbasm)

Source per stream: gfx/rle/NAME_AAAA.png (the decoded 2bpp tiles) and
gfx/rle/NAME_AAAA.ops (line 1: rgbgfx flags; line 2: the exact command list
c/C copy, f/F fill, endXX, as in mn-rle scripts/rle/README.md). The retail
packer is not greedy everywhere, so the list is kept to rebuild the bytes
exactly. build writes out/gen/rlegfx/NAME.asm: one label per stream and db
lines of the packed bytes, back to back in address order.
src/gfx/NAME_rle.asm INCLUDEs that file.

Stream format and rlelib.py are from the data-rle track (mn-rle).
"""
import os, pathlib, re, subprocess, sys
sys.path.insert(0, os.path.dirname(__file__))
from rlelib import decode, ops_tokens, encode_ops

ROOT = pathlib.Path(__file__).resolve().parents[2]
G = ROOT / "gfx/rle"
OUT = ROOT / "out/gen/rlegfx"
RGBGFX = os.environ.get("RGBGFX", "rgbgfx")


def extract(bank, start, end, name):
    rom = (ROOT / "roms/magination.gbc").read_bytes()
    p = bank * 0x4000 + start - 0x4000
    stop = bank * 0x4000 + end - 0x4000
    G.mkdir(parents=True, exist_ok=True)
    n = 0
    while p < stop:
        data, q, _ = decode(rom, p)
        toks = ops_tokens(rom, p)
        assert encode_ops(data, toks) == rom[p:q]
        assert data and len(data) % 16 == 0
        tiles = len(data) // 16
        w = min(16, tiles); trim = (-tiles) % w
        flags = f"-r {w}" + (f" -x {trim}" if trim else "")
        a = p - bank * 0x4000 + 0x4000
        stem = G / f"{name}_{a:04X}"
        raw = pathlib.Path(f"/tmp/{stem.name}.2bpp"); raw.write_bytes(data)
        subprocess.run([RGBGFX, *flags.split(), "-o", str(raw), f"{stem}.png"], check=True)
        stem.with_suffix(".ops").write_text(("-x %d" % trim if trim else "") + "\n" + " ".join(toks) + "\n")
        p = q; n += 1
    assert p == stop, (hex(p), hex(stop))
    print(f"{name}: {n} streams")


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    groups = {}
    for ops in sorted(G.glob("*.ops")):
        name, addr = ops.stem.rsplit("_", 1)
        groups.setdefault(name, []).append((int(addr, 16), ops))
    for name, items in groups.items():
        lines = [f"; Generated by scripts/own/rle_gfx.py from gfx/rle/{name}_*.png. Do not edit."]
        for addr, ops in sorted(items):
            flags, toks = ops.read_text().splitlines()[:2]
            two = OUT / f"{ops.stem}.2bpp"
            subprocess.run([RGBGFX, *flags.split(), "-o", str(two), str(ops.with_suffix(".png"))], check=True)
            packed = encode_ops(two.read_bytes(), toks.split())
            lines.append(f"{name.capitalize()}Rle_{addr:04X}::")
            for i in range(0, len(packed), 16):
                lines.append("    db " + ", ".join(f"${b:02X}" for b in packed[i:i + 16]))
        (OUT / f"{name}.asm").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    if sys.argv[1] == "extract":
        extract(int(sys.argv[2], 16), int(sys.argv[3], 16), int(sys.argv[4], 16), sys.argv[5])
    else:
        build()
