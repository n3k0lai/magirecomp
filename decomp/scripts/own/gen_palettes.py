#!/usr/bin/env python3
"""Generate src/palettes_bankNN.asm for RGB555 palette blocks that are
still INCBIN. Each line is one 4-color palette written with the rgb macro
(src/palette_macros.inc). A block is listed only if a loader points at it
and every word in it has bit 15 clear.

  $21 $5CC0-$67E7  357 palettes. Script op $66 (CallScriptBankedPtrThenCall2EE9,
                   fills $C76B, the OBJ palette staging) loads $5CC0 from bank
                   $21. The block ends where the bank $21 script lists' first
                   in-bank target (Script21_67E8) starts.
                   Entry records 0-108 point at 12-color (24-byte) sets inside it
                   (labels EntryPalettesNNN; see entry_palettes()).
  $40 $42C0-$43FF  5 sets of 8 palettes. Script op $66 loads $42C0 and $43C0,
                   op $78 (StagePairSourceThenCopyWords) loads $4300 and $4380;
                   unused slots hold $7C1F (magenta) filler.
"""
d = open("roms/magination.gbc", "rb").read()


def entry_palettes():
    """Entry records 0-108 (bank 4, RecordPtrFromId: id * $2D + $415B).
    Bytes $26-$28 are the pointer and bank DrawEntryFieldsVRAM0/1 pass to
    $358E (VRAM-0 path, palettes 0-2) or $35AD (VRAM-1 path, palettes 3-5):
    12 colors, 24 bytes, per entry. All 109 point into bank $21's block."""
    names = {}
    for i in range(109):
        o = 4 * 0x4000 + 0x415B - 0x4000 + i * 0x2D + 0x26
        ptr, bank = d[o] | d[o + 1] << 8, d[o + 2]
        assert bank == 0x21 and 0x5CC0 <= ptr < 0x67E8 and (ptr - 0x5CC0) % 8 == 0
        names.setdefault(ptr, []).append(i)
    return names
BLOCKS = {0x21: [(0x5CC0, 0x67E8, ())], 0x40: [(0x42C0, 0x4400, (0x42C0, 0x4300, 0x4340, 0x4380, 0x43C0))]}


def main():
    for bank, blocks in BLOCKS.items():
        out = [f"; Bank ${bank:02X} RGB555 palettes. Generated by scripts/own/gen_palettes.py.",
               "; One 4-color palette per line.", "", 'INCLUDE "src/palette_macros.inc"', ""]
        entry = entry_palettes() if bank == 0x21 else {}
        for start, end, labels in blocks:
            labels = set(labels) | {start}
            for a in range(start, end, 8):
                if a in labels or a in entry:
                    out.append(f"Palettes{bank:02X}_{a:04X}::")
                for i in entry.get(a, []):
                    out.append(f"EntryPalettes{i:03d}::  ; entry record {i}, 12 colors (24 B)")
                o = bank * 0x4000 + a - 0x4000
                cs = []
                for k in range(4):
                    w = d[o + 2 * k] | d[o + 2 * k + 1] << 8
                    assert w < 0x8000, hex(a)
                    cs.append(f"{w & 31:2d},{w >> 5 & 31:2d},{w >> 10 & 31:2d}")
                out.append(f"    rgb {',  '.join(cs)} ; ${a:04X}")
            out.append("")
        open(f"src/palettes_bank{bank:02x}.asm", "w").write("\n".join(out))
        print(f"{bank:02X} ok")


if __name__ == "__main__":
    main()
