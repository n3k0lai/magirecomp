#!/usr/bin/env python3
"""Generate src/map_sources_bank4f.asm: bank $4F $4000-$559E, 369 records of
five (pointer, bank) far pointers, the layout LoadFiveBankedMapSources
(bank 0 $2E15) reads from BC:
  0 BG palettes: 32 colors copied to $C72B (StageC72BThenBank7)
  1 CopyMapRecords source (both VRAM banks)
  2 block copied to WRAM bank 2 (CopyBlockToWRAMBank2)
  3 map header + UnpackBytes stream for WRAM bank 3 (UnpackHeaderWRAMBank3)
  4 block unpacked into WRAM bank 5 (UnpackBlockWRAMBank5)
The records run back to back; every one of the 1845 pointers is in
$4000-$7FFF and every slot-0 target is 32 valid RGB555 words.
"""
d = open("roms/magination.gbc", "rb").read()
B, N = 0x4F * 0x4000, 369


def main():
    out = ["; Bank $4F $4000-$559E: map source records for LoadFiveBankedMapSources.",
           "; Generated by scripts/own/gen_map_sources.py. Each record is five",
           "; far pointers: palettes, map records, WRAM-2 block, WRAM-3 map, WRAM-5 block.", "",
           "MACRO map_sources", "    REPT 5", "        dw \\1", "        db \\2", "        SHIFT 2",
           "    ENDR", "ENDM", ""]
    for i in range(N):
        o = B + 15 * i
        t = [(d[o + 3 * k] | d[o + 3 * k + 1] << 8, d[o + 3 * k + 2]) for k in range(5)]
        assert all(0x4000 <= p < 0x8000 and 2 <= b < 0x80 for p, b in t)
        p, b = t[0]
        q = b * 0x4000 + p - 0x4000
        assert all(d[q + 2 * j + 1] < 0x80 for j in range(32))
        out.append(f"MapSources4F_{i:03d}::  ; ${0x4000 + 15 * i:04X}")
        out.append("    map_sources " + ", ".join(f"${p:04X}, ${b:02X}" for p, b in t))
    out.append("MapSources4FEnd::")
    open("src/map_sources_bank4f.asm", "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
