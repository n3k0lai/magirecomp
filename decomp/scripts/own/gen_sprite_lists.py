#!/usr/bin/env python3
"""Generate src/sprite_lists_bankNN.asm for the sprite lists that open
banks $0E, $0F, $10, $11, $20 and $25. Each bank begins with lists that
QueueSpriteList reads (records of Y, X, tile, attr; $80 ends a list).
The lists stop where the first record has a Y or X outside -64..+64; the
rest of the bank is sprite-animation script bytecode (opcodes $46, $4C,
$4D...), whose $4C/$4D operands point back at these lists. That part is
left as INCBIN for the script-bytecode track.

Prints, per bank, the end address so the scaffold split can be checked.
"""
ROM = "roms/magination.gbc"
d = open(ROM, "rb").read()
BANKS = (0x0E, 0x0F, 0x10, 0x11, 0x20, 0x25, 0x41)
# Lists that do not open their bank: bank -> first list offset. Bank $41
# holds tiles up to $68FF (gfx/bank65_gfx.png), then lists, then scripts.
START = {0x41: 0x2900}


def small(v):
    return v >= 0xC0 or v <= 0x40


def parse(b):
    x = d[b * 0x4000:(b + 1) * 0x4000]
    i, lists = START.get(b, 0), []
    while True:
        j, recs = i, []
        while x[j] != 0x80:
            r = x[j:j + 4]
            if not (small(r[0]) and small(r[1])):
                return lists, i
            recs.append(r)
            j += 4
        lists.append((i, recs))
        i = j + 1


def s8(v):
    return v - 256 if v >= 0x80 else v


def main():
    for b in BANKS:
        lists, stop = parse(b)
        s0 = START.get(b, 0)
        out = [f"; Bank ${b:02X} ${0x4000 + s0:04X}-${0x4000 + stop - 1:04X}: {len(lists)} sprite lists for",
               "; QueueSpriteList. Generated by scripts/own/gen_sprite_lists.py.",
               "; The animation scripts after these lists point at them by address.", "",
               'INCLUDE "src/sprite_macros.inc"', ""]
        for n, (a, recs) in enumerate(lists):
            out.append(f"SpriteList{b:02X}_{n:02d}::  ; ${0x4000 + a:04X}")
            for r in recs:
                out.append(f"    sprite {s8(r[0]):4d}, {s8(r[1]):4d}, ${r[2]:02X}, ${r[3]:02X}")
            out.append("    sprites_end")
            out.append("")
        open(f"src/sprite_lists_bank{b:02x}.asm", "w").write("\n".join(out))
        print(f"{b:02X} {stop:04X}")


if __name__ == "__main__":
    main()
